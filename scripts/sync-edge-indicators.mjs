// Copies the entry-chart math (src/utils/indicators.js, signalSuite.js,
// entryEvents.js)
// into supabase/functions/_shared/ so the entry-scan edge function runs the
// exact same code as the browser. Edit the src/ files, then run
//   npm run indicators:sync
// `--check` exits 1 when a copy is out of date (run by indicators:check).
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const FILES = ['indicators.js', 'signalSuite.js', 'entryEvents.js']
const HEADER = '// GENERATED by scripts/sync-edge-indicators.mjs from src/utils/ — do not edit here.\n'
const check = process.argv.includes('--check')
let stale = []
for (const f of FILES) {
  const src = HEADER + readFileSync(`src/utils/${f}`, 'utf8')
  const dst = `supabase/functions/_shared/${f}`
  const cur = existsSync(dst) ? readFileSync(dst, 'utf8') : null
  if (cur === src) continue
  if (check) stale.push(dst)
  else { writeFileSync(dst, src); console.log(`wrote ${dst}`) }
}
if (check) {
  if (stale.length) { console.error(`out of date (run npm run indicators:sync): ${stale.join(', ')}`); process.exit(1) }
  console.log('edge indicator copies up to date')
}
