// Copies the NIGHTFLOW engine (src/utils/orderflow/) into the dxlink-worker
// (live engine) and dilution.js into supabase/functions/_shared/ (the
// orderflow-dilution edge function), so every runtime runs the same code.
// Edit src/utils/orderflow/, then `npm run orderflow:sync`.
// `--check` exits 1 when a copy is out of date (run by orderflow:check).
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs'

const HEADER = '// GENERATED by scripts/sync-orderflow.mjs from src/utils/orderflow/ — do not edit here.\n'
const pairs = readdirSync('src/utils/orderflow').filter((f) => f.endsWith('.js')).map((f) => [`src/utils/orderflow/${f}`, `dxlink-worker/src/orderflow/${f}`])
pairs.push(['src/utils/orderflow/dilution.js', 'supabase/functions/_shared/orderflowDilution.js'])
const check = process.argv.includes('--check')
mkdirSync('dxlink-worker/src/orderflow', { recursive: true })
const stale = []
for (const [from, to] of pairs) {
  const src = HEADER + readFileSync(from, 'utf8')
  const cur = existsSync(to) ? readFileSync(to, 'utf8') : null
  if (cur === src) continue
  if (check) stale.push(to)
  else { writeFileSync(to, src); console.log(`wrote ${to}`) }
}
if (check) {
  if (stale.length) { console.error(`out of date (run npm run orderflow:sync): ${stale.join(', ')}`); process.exit(1) }
  console.log('orderflow copies up to date')
}
